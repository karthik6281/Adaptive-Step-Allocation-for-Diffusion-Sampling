#!/usr/bin/env python3
"""Example-image figure for the step-placement paper (Stable Diffusion 1.5, N = 8).

Reads the per-prompt scores in sdpost_sd15_coco_B8_n64.npz (written by sd_checks.py) and the
PNGs that sd_checks.py rendered next to it, picks three prompts by a fixed rule (the 25th,
50th and 75th percentile of the per-prompt LPIPS gain), and writes resized JPEGs plus the
LaTeX rows of the figure. The LPIPS printed under each image is the stored score of that
image: batched rollouts for uniform spacing and the shared schedules, single-prompt rollouts
for the per-prompt schedule, as in sd_checks.py.

    python rollouts/paper_samples.py --sdpost data/rollouts/runs1/sdpost_sd15_coco_B8_n64.npz \
        --search data/rollouts/runs1/search_sd15_coco_B8_n64_sw10.npz \
        --images <folder of PNGs rendered by sd_checks.py --render> --out build/paper

The PNGs (64 prompts x 5 schedules) are not in this repository; the figures are in the
report.
"""
import argparse
import os

import numpy as np
from PIL import Image

COLS = ("ref", "uniform_B8", "shared_B8", "shared_B9", "perprompt_B8")
QUANTILES = (0.25, 0.5, 0.75)
SIDE = 384          # pixels; about 310 dpi at the printed width


def tex_escape(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdpost", required=True)
    ap.add_argument("--search", required=True)
    ap.add_argument("--images", required=True)
    ap.add_argument("--out", required=True, help="paper folder (writes figures/samples/, tables/)")
    args = ap.parse_args()

    post = np.load(args.sdpost)
    if [str(m) for m in post["metrics"]][0] != "lpips":
        raise SystemExit("unexpected metric order in sdpost")
    lp = {k: np.asarray(post[k], np.float64)[0] for k in
          ("uniform_B", "shared_B", "shared_B1", "perprompt_own", "perprompt_sharedB")}
    prompts = [str(p) for p in np.load(args.search)["prompts"]]
    n = len(prompts)
    gain = lp["perprompt_sharedB"] - lp["perprompt_own"]          # single-prompt path
    order = np.argsort(gain, kind="stable")
    picks = [int(order[int(round(q * (n - 1)))]) for q in QUANTILES]

    img_dir = os.path.join(args.out, "figures", "samples")
    os.makedirs(img_dir, exist_ok=True)
    rows = ["% Generated by utils/paper_samples.py. Do not edit by hand."]
    for r, i in enumerate(picks):
        for c in COLS:
            im = Image.open(os.path.join(args.images, c, f"{i:02d}.png")).convert("RGB")
            if im.size != (512, 512):
                raise SystemExit(f"{c}/{i:02d}.png is {im.size}, expected 512x512")
            im.resize((SIDE, SIDE), Image.LANCZOS).save(
                os.path.join(img_dir, f"p{i:02d}_{c}.jpg"), quality=92, optimize=True)
        cells = [rf"\includegraphics[width=\sampw]{{figures/samples/p{i:02d}_{c}.jpg}}" for c in COLS]
        scores = ["", f"{lp['uniform_B'][i]:.3f}", f"{lp['shared_B'][i]:.3f}",
                  f"{lp['shared_B1'][i]:.3f}", f"{lp['perprompt_own'][i]:.3f}"]
        rows.append(rf"\multicolumn{{5}}{{l}}{{\scriptsize\itshape ``{tex_escape(prompts[i])}''}} \\")
        rows.append(" & ".join(cells) + r" \\")
        rows.append(" & ".join(rf"\scriptsize {s}" if s else "" for s in scores)
                    + (r" \\[4pt]" if r < len(picks) - 1 else r" \\"))
        print(f"  prompt {i:2d}  gain {gain[i]:.4f}  uniform {lp['uniform_B'][i]:.3f}  "
              f"shared8 {lp['shared_B'][i]:.3f}  shared9 {lp['shared_B1'][i]:.3f}  "
              f"own {lp['perprompt_own'][i]:.3f}  {prompts[i]}")
    os.makedirs(os.path.join(args.out, "tables"), exist_ok=True)
    with open(os.path.join(args.out, "tables", "samples.tex"), "w") as fh:
        fh.write("\n".join(rows) + "\n")
    print(f"wrote {len(picks) * len(COLS)} JPEGs and tables/samples.tex")

    # eight more prompts at the 1/16, 3/16, ..., 15/16 quantiles of the gain: reference,
    # shared N and per-prompt N, two prompts per row, in order of gain
    more = [int(order[int(round((2 * j + 1) / 16 * (n - 1)))]) for j in range(8)]
    if set(more) & set(picks) or len(set(more)) != 8:
        raise SystemExit("extra prompts overlap the first figure")
    cols3 = ("ref", "shared_B8", "perprompt_B8")
    rows = ["% Generated by utils/paper_samples.py. Do not edit by hand."]
    for r in range(4):
        pair = more[2 * r:2 * r + 2]
        caps, imgs, nums = [], [], []
        for side, i in enumerate(pair):
            for c in cols3:
                im = Image.open(os.path.join(args.images, c, f"{i:02d}.png")).convert("RGB")
                im.resize((320, 320), Image.LANCZOS).save(
                    os.path.join(img_dir, f"p{i:02d}_{c}.jpg"), quality=92, optimize=True)
            gap = r"@{\hspace{\sampgap}}" if side == 0 else ""   # same gap as the image rows
            caps.append(rf"\multicolumn{{3}}{{>{{\raggedright\arraybackslash}}p{{\samprow}}{gap}}}"
                        rf"{{\scriptsize\itshape ``{tex_escape(prompts[i])}''}}")
            imgs += [rf"\includegraphics[width=\sampwb]{{figures/samples/p{i:02d}_{c}.jpg}}"
                     for c in cols3]
            nums += ["", rf"\scriptsize {lp['shared_B'][i]:.3f}",
                     rf"\scriptsize {lp['perprompt_own'][i]:.3f}"]
        rows.append(" & ".join(caps) + r" \\")
        rows.append(" & ".join(imgs) + r" \\")
        rows.append(" & ".join(nums) + (r" \\[4pt]" if r < 3 else r" \\"))
        for i in pair:
            print(f"  more {i:2d}  gain {gain[i]:.4f}  shared8 {lp['shared_B'][i]:.3f}  "
                  f"own {lp['perprompt_own'][i]:.3f}")
    with open(os.path.join(args.out, "tables", "samples_more.tex"), "w") as fh:
        fh.write("\n".join(rows) + "\n")
    print("wrote 24 more JPEGs and tables/samples_more.tex")


if __name__ == "__main__":
    main()
